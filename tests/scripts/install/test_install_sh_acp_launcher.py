PANERGOS_AGENT_BLOCK = re.compile(
    r'(rm -f "\$command_link_dir/panergos-agent".*?'
    r'log_success "Installed panergos-agent launcher[^\n]*\n)',
    re.S,
)


def _extract_panergos_agent_shim_block() -> str:
    match = PANERGOS_AGENT_BLOCK.search(INSTALL_SH.read_text(encoding="utf-8"))
    assert match, (
        "could not locate the panergos-agent launcher block in scripts/install.sh — "
        "if it was renamed, update this test with it"
    )
    return match.group(1)


def _run_panergos_agent_block(tmp_path: Path, use_venv: str) -> Path | None:
    """Execute the extracted panergos-agent block with the env vars setup_path() sets."""
    if use_venv == "false":
        # --no-venv: panergos-agent is NOT installed by this block (handled
        # elsewhere), so there's nothing to test here.
        return None

    command_link_dir = tmp_path / "local_bin"
    command_link_dir.mkdir()
    panergos_bin = tmp_path / "venv" / "bin" / "python"
    panergos_bin.parent.mkdir(parents=True)
    panergos_bin.write_text("#!/bin/sh\n", encoding="utf-8")
    install_dir = tmp_path / "install"
    install_dir.mkdir()

    script = (
        "set -e\n"
        f"PANERGOS_BIN={_shell_path(panergos_bin)}\n"
        f"INSTALL_DIR={_shell_path(install_dir)}\n"
        f"command_link_dir={_shell_path(command_link_dir)}\n"
        f"command_link_display_dir={_shell_path(command_link_dir)}\n"
        f"USE_VENV={use_venv}\n"
        "log_success(){ :; }\n" + _extract_panergos_agent_shim_block()
    )
    result = subprocess.run(
        ["bash"],
        input=script.encode("utf-8"),
        capture_output=True,
        cwd=tmp_path,
    )
    assert result.returncode == 0, (
        f"panergos-agent shim block failed:\nstdout={result.stdout}\nstderr={result.stderr}"
    )
    return command_link_dir / "panergos-agent"


def test_venv_install_writes_executable_panergos_agent_launcher(tmp_path):
    """venv install must write a user-executable panergos-agent launcher."""
    shim = _run_panergos_agent_block(tmp_path, "true")
    assert shim is not None
    assert shim.is_file()
    assert _is_shell_executable(shim), "launcher must be user-executable"

    text = shim.read_text(encoding="utf-8")
    assert "unset PYTHONPATH" in text
    assert "unset PYTHONHOME" in text
    assert "run_agent.py" in text, "panergos-agent must dispatch to run_agent.py"


def test_panergos_agent_launcher_cleanup_on_uninstall(tmp_path):
    """Uninstall removes panergos-agent alongside primary and compatibility shims."""
    from panergos_cli.uninstall import remove_wrapper_script

    # Simulate a panergos-agent wrapper in the user-local location
    local_shim = tmp_path / ".local" / "bin" / "panergos-agent"
    local_shim.parent.mkdir(parents=True)
    local_shim.write_text("#!/usr/bin/env bash\nexec panergos-agent\n", encoding="utf-8")

    with patch.object(Path, "home", return_value=tmp_path):
        removed = remove_wrapper_script()

    assert local_shim in removed, "local panergos-agent wrapper must be removed"
